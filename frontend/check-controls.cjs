const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const app=fs.readFileSync(__dirname+'/app.js','utf8').replace('  /* SERVICE_CHECKS */',fs.readFileSync(__dirname+'/service-checks.js','utf8'));
const model=vm.runInNewContext(app.split('  const KEY=')[0]+`\nconst state={m:0,playing:true,anchor:0};return {REGION_DATA,STAGES,plantSnapshot,controlledPlant,plcSettings,telemetrySources,createTelemetryFeed,updateTelemetryFeed,telemetryFeedRows,telemetrySignalProfile};})();`,{Intl,Date});
let checks=0;
const check=(value,label)=>{assert.ok(value,label);checks++;};
const region=model.REGION_DATA[3],base={...model.plantSnapshot(region,0),cursor:0},at=100000;
const record=(patch,b=base)=>({...model.plcSettings(b,patch),stage:0,cursor:0,at,from:{...b,localTemp:b.temp}});
const plant=(patch,seconds=10)=>model.controlledPlant(base,record(patch),at+seconds*1000);
for(const r of model.REGION_DATA)for(const stage of model.STAGES){
  const p={...model.plantSnapshot(r,stage.start),cursor:stage.start};
  const auto=model.controlledPlant(p,null,at);
  check(auto.service===p.service&&auto.valve===p.valve&&auto.pumps.length===6,'no command preserves the scenario / '+r.id+'/'+stage.index);
}
const off=Array(6).fill(true);off[2]=false;
const stopped=plant({pumps:off});
check(stopped.flow===0&&stopped.pressure===0,'distribution stop removes flow and pressure');
check(stopped.service<10,'distribution stop reduces service over time');
const fillOff=Array(6).fill(true);fillOff[0]=false;
check(plant({pumps:fillOff}).pump===0&&plant({pumps:fillOff}).actual<base.actual,'supply stop halts filling and lowers level');
check(plant({driveHz:44}).actual>plant({driveHz:11}).actual,'higher supply frequency increases tank level');
const heatOff=Array(6).fill(true);heatOff[1]=false;
check(plant({pumps:heatOff}).localTemp<base.temp,'heating stop cools the process');
check(plant({heat:75}).temp>plant({heat:30}).temp,'temperature follows the selected target');
check(plant({valve:0}).flow===0&&plant({valve:70}).flow>0,'valve affects distribution flow');
const branchOff=Array(6).fill(true);branchOff[3]=false;
const partial=plant({pumps:branchOff},25);
check(partial.branchServices[0]<1&&partial.branchServices[1]>99,'one branch stop is independent of other facilities');
check(Math.abs(partial.service-partial.branchServices.reduce((s,n)=>s+n,0)/3)<1e-9,'overall service equals branch service average');
check(plant({driveHz:0}).pumps[0]===false,'zero frequency stops the supply pump');
const bounds=model.plcSettings(base,{driveHz:-20,valve:300,heat:200});
check(bounds.driveHz===0&&bounds.valve===100&&bounds.heat===85,'control values are bounded');
const bad=model.plcSettings(base,{driveHz:NaN,valve:Infinity,heat:'bad'});
check(bad.driveHz===22&&bad.valve===70&&bad.heat===48,'invalid values retain valid setpoints');
const stale={...record({valve:0}),stage:5,cursor:125};
check(model.controlledPlant(base,stale,at+1000).valve===70,'commands from another stage do not leak');
check(model.controlledPlant(base,record({valve:0}),at-1).valve===70,'future-dated controls are not applied');
const measureAt=model.STAGES[4].start+5,commandAt=model.STAGES[5].start+5,outageAt=model.STAGES[6].start;
const damaged={...model.plantSnapshot(region,measureAt),cursor:measureAt};
const manual=model.controlledPlant(damaged,{...record({valve:70},damaged),stage:4,cursor:measureAt},at+1000);
check(Math.abs(manual.bias-30)<.001,'local commands do not erase an independent measurement discrepancy');
const manualRows=model.telemetrySources(measureAt,undefined,new Map([[region.id,manual]]));
const manualSource=manualRows.find(s=>s.id==='GO-PLC-01');
check(manualSource.channels[0].tone==='bad'&&manualSource.channels[1].tone==='good','authorized local commands and corrupted measurements are separate');
const feed=model.createTelemetryFeed('controls',at);
model.updateTelemetryFeed(feed,'controls',0,at);
const first=model.telemetryFeedRows(feed,at).find(s=>s.id==='KR-ZPT-01');
check(first.link.quality===first.asset.values.signal,'signal metric equals the received packet value');
const profile=model.telemetrySignalProfile(first,at);
check(profile.bars.length===36&&profile.wave.length===65,'restored equalizer has 36 bars and a waveform');
check(profile.bars.every(v=>Number.isFinite(v)&&v>=0&&v<=1),'signal bars remain in bounds');
check(profile.bars.some((v,i)=>v!==model.telemetrySignalProfile(first,at+700).bars[i]),'restored signal bars fluctuate in fixed positions');
const lost=model.telemetrySignalProfile({...first,offline:true},at);
check(lost.bars.every(v=>v===0)&&lost.quality===null,'lost link clears fresh signal activity');
const changed=model.updateTelemetryFeed(feed,'controls',0,at,new Map([[region.id,stopped]]),1);
check(changed&&model.telemetryFeedRows(feed,at).find(s=>s.id==='GO-PLC-01').plant.flow===0,'control revisions reach telemetry within the same sample interval');
model.updateTelemetryFeed(feed,'controls',commandAt,at+1000);
const last=model.telemetryFeedRows(feed,at+1000).find(s=>s.id==='GO-PLC-01');
model.updateTelemetryFeed(feed,'controls',outageAt,at+2000);
const offline=model.telemetryFeedRows(feed,at+2000).find(s=>s.id==='GO-PLC-01');
check(offline.plant.shown===last.plant.shown&&offline.link===null,'outage freezes HMI values and clears fresh link metrics');
console.log(checks+' control, process, synchronization and data-to-graph checks passed.');
